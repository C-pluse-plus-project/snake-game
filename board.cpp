Board::Board() {
    loadMap(1);
}

void Board::loadMap(const int stage) {
    const int (*selectedMap)[BOARD_SIZE] = initialMap;

    if (stage == 1) {
        selectedMap = initialMap;
    }
    else if (stage == 2) {
        selectedMap = secondMap;
    }
    else if (stage == 3) {
        selectedMap = thirdMap;
    }
    else if (stage == 4) {
        selectedMap = fourthMap;
    }

    for (int y = 0; y < BOARD_SIZE; y++) {
        for (int x = 0; x < BOARD_SIZE; x++) {
            map[y][x] = selectedMap[y][x] == GATE ? WALL : selectedMap[y][x];
        }
    }

    Gate::placePair();
}

int Board::getSize() const {
    return BOARD_SIZE;
}

int Board::getCell(const int y, const int x) const {
    return map[y][x];
}

void Board::setCell(const int y, const int x, const int value) {
    map[y][x] = value;
}

bool Board::isWall(const int y, const int x) const {
    return map[y][x] == WALL || map[y][x] == IMMUNE_WALL;
}

void Board::draw() const {
    for (int y = 0; y < BOARD_SIZE; y++) {
        for (int x = 0; x < BOARD_SIZE; x++) {
            char ch = ' ';

            switch (map[y][x]) {
            case WALL:
                ch = '#';
                break;
            case IMMUNE_WALL:
                ch = 'X';
                break;
            case SNAKE_HEAD:
                ch = 'H';
                break;
            case SNAKE_BODY:
                ch = 'B';
                break;
            case GATE:
                ch = 'G';
                break;
            case GROWTH_ITEM:
                ch = '+';
                break;
            case POISON_ITEM:
                ch = '-';
                break;
            case SPEED_ITEM:
                ch = 'S';
                break;
            default:
                break;
            }

            mvprintw(y + 1, x * 2 + 1, "%c ", ch);
        }
    }
}
